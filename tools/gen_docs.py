def source_strings(root=ROOT):
    """String literals of the package and of the native core, where error messages are raised."""
    strings = []
    for path in (root/"src"/"qdjj_solver").rglob("*.py"):
        for node in ast.walk(ast.parse(path.read_text())):
            if isinstance(node, ast.Constant) and isinstance(node.value, str):
                strings.append(node.value)
            elif isinstance(node, ast.JoinedStr):
                strings.append("".join(v.value if isinstance(v, ast.Constant) else "{}" for v in node.values))
    core = root/"cpp"/"core.cpp"
    if core.is_file():
        strings += re.findall(r'"((?:[^"\\]|\\.)*)"', core.read_text())
    return strings


