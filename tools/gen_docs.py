def excerpt(relative, name):
    source = (ROOT/relative).read_text()
    match = re.search(rf"^[ \t]*# BEGIN handbook: {re.escape(name)}\n(.*?)^[ \t]*# END handbook: {re.escape(name)}$",
                      source, re.M | re.S)
    if match is None:
        raise ValueError(f"{relative}: missing excerpt {name}")
    return textwrap.dedent(match.group(1)).rstrip()


