def h1(path):
    """The first level-one heading of a Markdown page, outside code fences."""
    fence = None
    for line in path.read_text().split("\n"):
        marker = re.match(r" {0,3}(`{3,}|~{3,})", line)
        if marker:
            fence = None if fence and marker.group(1)[0] == fence[0] else (fence or marker.group(1))
        elif fence is None and line.startswith("# "):
            return line[2:].strip()
    raise SystemExit(f"{path}: no level-one heading")


def latex_text(text):
    """Markdown heading text (with `code`) as LaTeX text."""
    def escape(chunk):
        return re.sub(r"([_&%#$])", r"\\\1", chunk)
    parts = re.split(r"`([^`]+)`", text)
    return "".join(escape(part) if i % 2 == 0 else f"\\texttt{{{escape(part)}}}" for i, part in enumerate(parts))


