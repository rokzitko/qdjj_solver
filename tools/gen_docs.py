def _markdown_math(text):
    """GitHub inline math: protect spans containing escaped punctuation, as AGENTS.md requires."""
    def span(match):
        body = match.group(1)
        return f"$`{body}`$" if re.search(r"\\[^A-Za-z]", body) else f"${body}$"
    return re.sub(r"\$([^$]+)\$", span, text)


