def _argument_rows(parser):
    rows = []
    for action in parser._actions:
        if isinstance(action, (argparse._HelpAction, argparse._SubParsersAction)):
            continue
        name = ", ".join(action.option_strings) if action.option_strings else action.dest
        if not action.help:
            raise SystemExit(f"command-line argument {name} has no help text")
        if isinstance(action, (argparse._StoreTrueAction, argparse._VersionAction)):
            values = "no value"
        elif action.choices:
            values = ", ".join(f"`{c}`" for c in action.choices)
        else:
            values = getattr(action.type, "__name__", "text").replace("Path", "path").replace("str", "text")
        required = action.required or not action.option_strings
        empty = action.default in (None, False, argparse.SUPPRESS)
        default = "required" if required else ("" if empty else f"`{action.default}`")
        rows.append(f"| `{name}` | {values} | {default} | {action.help[0].upper()}{action.help[1:]} |")
    return rows


