def api_page():
    seen = set()
    lines = [NOTICE, "", "# API reference", "",
             "Each public object is documented once, under the first module below that exports it; the",
             "lists are the modules' `__all__`. The legacy `qpsolver` package re-exports",
             "`qdjj_solver.qp_solver`, so those entries also serve as its reference. Option and result fields are",
             "also tabulated in the [option](options.md) and [result](results.md) references.", ""]
    for module_name, title, summary in API_MODULES:
        module = importlib.import_module(module_name)
        lines += [f"## {title}", "", summary, "", "```{eval-rst}", f".. py:currentmodule:: {module_name}", "```", ""]
        for name in module.__all__:
            obj = getattr(module, name)
            if name.startswith("__") or id(obj) in seen:
                continue
            seen.add(id(obj))
            if isinstance(obj, type):
                lines += ["```{eval-rst}", f".. autoclass:: {module_name}.{name}", "   :members:", "   :undoc-members:", "```", ""]
            elif callable(obj):
                lines += ["```{eval-rst}", f".. autofunction:: {module_name}.{name}", "```", ""]
            else:
                lines += ["```{eval-rst}", f".. autodata:: {module_name}.{name}", "   :no-value:", "```", ""]
    lines += ["## Supported supplementary helpers", "",
              "These qualified submodule functions support the workflows in this handbook. Legacy DMRG",
              "helpers use their own reference interfaces, with the signatures documented below.", ""]
    for name in API_HELPERS:
        obj = resolve_object(name)
        if not inspect.getdoc(obj):
            raise ValueError(f"{name}: missing helper docstring")
        lines += ["```{eval-rst}", f".. autofunction:: {name}", "```", ""]
    return "\n".join(lines)


