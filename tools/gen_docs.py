@dataclasses.dataclass
class Field:
    name: str
    annotation: str
    default: str | None
    doc: str | None
    line: int


def dataclass_fields(path, cls):
    """Fields of a dataclass with their annotation, default and attribute docstring, from source."""
    source = path.read_text()
    tree = ast.parse(source)
    node = next(n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == cls)
    fields = []
    for index, item in enumerate(node.body):
        if not (isinstance(item, ast.AnnAssign) and isinstance(item.target, ast.Name)):
            continue
        annotation = ast.get_source_segment(source, item.annotation)
        if annotation.startswith("ClassVar"):
            continue
        default = None
        if item.value is not None:
            value = item.value
            if isinstance(value, ast.Call) and getattr(value.func, "id", "") == "field":
                factory = next((k.value for k in value.keywords if k.arg == "default_factory"), None)
                explicit = next((k.value for k in value.keywords if k.arg == "default"), None)
                default = (f"{ast.get_source_segment(source, factory)}()" if factory is not None else
                           ast.get_source_segment(source, explicit) if explicit is not None else None)
            else:
                default = ast.get_source_segment(source, value)
        following = node.body[index + 1] if index + 1 < len(node.body) else None
        doc = None
        if isinstance(following, ast.Expr) and isinstance(following.value, ast.Constant) \
                and isinstance(following.value.value, str):
            doc = " ".join(following.value.value.split())
        fields.append(Field(item.target.id, annotation, default, doc, item.lineno))
    return fields


def markdown_text(doc):
    """Docstring text (plain text with ``literals``) as Markdown table-cell text."""
    return re.sub(r"``(.+?)``", r"`\1`", doc).replace("|", "\\|")


def code(text):
    return "`" + text.replace("|", "\\|") + "`"


