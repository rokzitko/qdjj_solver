def resolve_object(name):
    """Resolve a documented qualified name, including nested class methods."""
    parts = name.split(".")
    for size in range(len(parts), 0, -1):
        try:
            value = importlib.import_module(".".join(parts[:size]))
        except ModuleNotFoundError as error:
            if error.name not in (".".join(parts[:size]), ".".join(parts[:size-1])):
                raise
            continue
        for part in parts[size:]:
            value = getattr(value, part)
        return value
    raise ValueError(f"cannot resolve {name}")


def parameter_entries():
    entries = tomllib.loads((ROOT/"docs"/"parameters.toml").read_text())["callable"]
    for entry in entries:
        signature = inspect.signature(resolve_object(entry["name"]))
        names = {name for name in signature.parameters if name not in ("self", "cls")}
        if names != set(entry["parameters"]):
            raise ValueError(f"{entry['name']}: parameter documentation differs from signature: "
                             f"missing={names-set(entry['parameters'])}, obsolete={set(entry['parameters'])-names}")
    return entries


