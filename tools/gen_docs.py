def _resolve(name):
    """Whether a code name of the concordance exists in the public API."""
    from qdjj_solver.common.models import OBSERVABLE_DOCS
    if name in OBSERVABLE_DOCS:
        return True
    parts = name.split(".")
    if parts[0] in ("qp_solver", "dmrg_solver"):
        return hasattr(importlib.import_module(f"qdjj_solver.{parts[0]}"), parts[1])
    for module_name in ("qdjj_solver", "qdjj_solver.qp_solver"):
        obj = importlib.import_module(module_name)
        for part in parts:
            fields = {f.name for f in dataclasses.fields(obj)} if dataclasses.is_dataclass(obj) else set()
            if hasattr(obj, part):
                obj = getattr(obj, part)
            elif part in fields or part in getattr(obj, "__annotations__", {}):
                obj = None
            else:
                break
        else:
            return True
    return False


