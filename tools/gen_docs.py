def _fields_or_raise(relative, cls):
    fields = dataclass_fields(SRC/relative, cls)
    missing = [f.name for f in fields if not f.doc]
    if missing:
        raise SystemExit(f"src/qdjj_solver/{relative}: {cls} fields without a docstring: {', '.join(missing)}")
    return fields


