def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if a committed generated file is stale")
    arguments = parser.parse_args(argv)
    stale = []
    for relative, content in outputs().items():
        path = ROOT/relative
        current = path.read_text() if path.is_file() else None
        if current == content:
            continue
        if arguments.check:
            stale.append(relative)
            diff = difflib.unified_diff((current or "").splitlines(), content.splitlines(), relative, "generated",
                                        lineterm="", n=1)
            print("\n".join(list(diff)[:40]))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
            print(f"wrote {relative}")
    if stale:
        print(f"stale generated files: {', '.join(stale)}; run python tools/gen_docs.py")
        return 1
    return 0


