"""Numbers quoted in the physics manual, taken from the tracked figure data.

    python -B quoted.py                   # write ../generated/quoted.tex and quoted.json
    python -B quoted.py --check           # fail if the committed files are stale
    python -B quoted.py --compare OLD     # values that moved beyond their last printed digit

Every ``fig_<name>.py`` may define ``quoted(record)``, which returns
``{key: (value, format)}`` for the record in ``data/<name>.json``; ``format`` is a
Python format specification (``".4f"``) or ``None`` for a ready string. The text
uses ``\\q{<name>.<key>}``, so recomputed data change the printed numbers and the
change appears in the review of the committed ``quoted.tex``. No solver and no
matplotlib are needed.
"""

from __future__ import annotations

import argparse
from decimal import Decimal, InvalidOperation
import importlib
import json
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
GENERATED = HERE.parent/"generated"


def collect():
    """{"figure.key": {"value", "text", "format"}} for every figure script with quoted()."""
    sys.path.insert(0, str(HERE))
    import manual_common as mc
    values = {}
    for script in sorted(HERE.glob("fig_*.py")):
        name = script.stem[4:]
        module = importlib.import_module(script.stem)
        if not hasattr(module, "quoted"):
            continue
        for key, (value, spec) in module.quoted(mc.load(name)).items():
            text = str(value) if spec is None else format(value, spec)
            values[f"{name}.{key}"] = dict(value=value if spec is not None else None, text=text, format=spec)
    return values


def render(values):
    tex = ["% Generated by docs/manual/scripts/quoted.py (make quoted) from data/*.json; do not edit."]
    tex += [f"\\defq{{{key}}}{{{entry['text']}}}" for key, entry in sorted(values.items())]
    return "\n".join(tex) + "\n", json.dumps(dict(sorted(values.items())), indent=1) + "\n"


def last_digit(text):
    """One unit of the last printed digit of a number, or None for text."""
    try:
        return float(Decimal(10) ** Decimal(text.replace("−", "-")).as_tuple().exponent)
    except (InvalidOperation, ValueError, TypeError):
        return None


def compare(old, new):
    """Keys whose printed text changed by more than one unit of the last digit (or appeared/vanished)."""
    changes = []
    for key in sorted(set(old) | set(new)):
        if key not in old or key not in new:
            changes.append((key, old.get(key, {}).get("text"), new.get(key, {}).get("text")))
            continue
        a, b = old[key], new[key]
        if a["text"] == b["text"]:
            continue
        unit = last_digit(a["text"])
        if unit is None or a["value"] is None or b["value"] is None or abs(b["value"] - a["value"]) > unit:
            changes.append((key, a["text"], b["text"]))
    return changes


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if the committed files are stale")
    parser.add_argument("--compare", type=Path, help="quoted.json of an earlier state of the data")
    arguments = parser.parse_args(argv)
    values = collect()
    tex, record = render(values)
    if arguments.compare:
        changes = compare(json.loads(arguments.compare.read_text()), values)
        for key, before, after in changes:
            print(f"{key}: {before} -> {after}")
        print(f"{len(changes)} quoted value(s) changed beyond their printed precision")
        return 1 if changes else 0
    targets = {GENERATED/"quoted.tex": tex, GENERATED/"quoted.json": record}
    if arguments.check:
        stale = [path.name for path, content in targets.items()
                 if not path.is_file() or path.read_text() != content]
        if stale:
            print(f"stale: {', '.join(stale)}; run make quoted")
        return 1 if stale else 0
    for path, content in targets.items():
        path.parent.mkdir(exist_ok=True)
        path.write_text(content)
    print(f"wrote {len(values)} quoted values")
    return 0


if __name__ == "__main__":
    sys.exit(main())
